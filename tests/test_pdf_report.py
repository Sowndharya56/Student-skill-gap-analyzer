def test_pdf_generation_returns_bytes(sample_report_data):
    """Verify that generate_pdf_report returns binary bytes."""
    pdf_bytes = generate_pdf_report(**sample_report_data)
    assert isinstance(pdf_bytes, bytes)


def test_pdf_generation_is_not_empty(sample_report_data):
    """Verify that generated PDF has substantial size (> 5KB for multi-page audit report)."""
    pdf_bytes = generate_pdf_report(**sample_report_data)
    assert len(pdf_bytes) > 5000


def test_pdf_starts_with_valid_pdf_signature(sample_report_data):
    """Verify that the generated bytes start with the official standard '%PDF' magic header."""
    pdf_bytes = generate_pdf_report(**sample_report_data)
    assert pdf_bytes.startswith(b"%PDF")


def test_pdf_generation_with_dict_arg(sample_report_data):
    """Verify that generate_pdf_report accepts a single dictionary as positional or keyword arg."""
    pdf_bytes_pos = generate_pdf_report(sample_report_data)
    assert isinstance(pdf_bytes_pos, bytes)
    assert pdf_bytes_pos.startswith(b"%PDF")
    
    pdf_bytes_kw = generate_pdf_report(report_data=sample_report_data)
    assert isinstance(pdf_bytes_kw, bytes)
    assert pdf_bytes_kw.startswith(b"%PDF")


def test_pdf_generation_with_default_arguments():
    """Verify that generate_pdf_report works with default parameters."""
    pdf_bytes = generate_pdf_report()
    assert isinstance(pdf_bytes, bytes)
    assert pdf_bytes.startswith(b"%PDF")
    assert len(pdf_bytes) > 1000


def test_pdf_generation_with_empty_or_none_data():
    """Verify that PDF generator handles empty dataframes, None lists, and empty structures safely."""
    pdf_bytes = generate_pdf_report(
        student_name="Test Student",
        degree="B.Sc",
        gpa=7.0,
        experience=0,
        projects=0,
        target_role="Software Engineer",
        readiness_metrics=None,
        recommendations=[],
        df_gaps=pd.DataFrame(),
        roadmap=[],
        df_priorities=pd.DataFrame(),
        learning_sequence=[],
        course_recs={}
    )
    assert isinstance(pdf_bytes, bytes)
    assert pdf_bytes.startswith(b"%PDF")


